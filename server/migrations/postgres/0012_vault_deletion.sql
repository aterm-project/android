-- PostgreSQL Vault deletion intent and durable external object deletion.
-- These rows deliberately have no Vault/account foreign key: they must remain
-- available after the Vault's cascading purge removes its catalogue rows.

CREATE TABLE vault_deletion_requests (
    request_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vault_id TEXT NOT NULL,
    requested_at BIGINT NOT NULL,
    purge_after BIGINT NOT NULL,
    actor_hash TEXT,
    cancelled_at BIGINT,
    purged_at BIGINT,
    CHECK (purge_after > requested_at),
    CHECK (cancelled_at IS NULL OR purged_at IS NULL),
    CHECK (actor_hash IS NULL OR actor_hash ~ '^[0-9a-f]{64}$')
);

CREATE UNIQUE INDEX idx_vault_deletion_one_pending
    ON vault_deletion_requests(vault_id)
    WHERE cancelled_at IS NULL AND purged_at IS NULL;

CREATE INDEX idx_vault_deletion_due
    ON vault_deletion_requests(purge_after, request_id)
    WHERE cancelled_at IS NULL AND purged_at IS NULL;

CREATE INDEX idx_vault_deletion_audit_retention
    ON vault_deletion_requests(COALESCE(purged_at, cancelled_at))
    WHERE cancelled_at IS NOT NULL OR purged_at IS NOT NULL;

-- Maintenance prunes a small ordered batch frequently, including on every
-- service node. This index keeps each pass bounded in both rows visited and
-- work needed to find the oldest retained event.
CREATE INDEX idx_audit_events_retention
    ON audit_events(occurred_at, event_id);

-- External storage keys are immutable and globally unique within a storage
-- identity. This prevents one Vault's purge worker from deleting bytes that a
-- second Vault still catalogues under the same key.
DO $migration$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM blob_objects
        WHERE storage_store_id IS NOT NULL
          AND storage_key IS NOT NULL
        GROUP BY storage_store_id, storage_key
        HAVING COUNT(*) > 1
    ) THEN
        RAISE EXCEPTION USING
            MESSAGE = 'cannot create idx_blob_objects_storage_identity: duplicate external storage identities already exist in blob_objects',
            HINT = 'Find conflicts with SELECT storage_store_id, storage_key, array_agg(vault_id || ''/'' || object_id ORDER BY vault_id, object_id) FROM blob_objects WHERE storage_store_id IS NOT NULL AND storage_key IS NOT NULL GROUP BY storage_store_id, storage_key HAVING COUNT(*) > 1. Reconcile the catalogue and assign each live object a unique storage key, then rerun the migration. No existing rows were changed.';
    END IF;
END;
$migration$;

CREATE UNIQUE INDEX idx_blob_objects_storage_identity
    ON blob_objects(storage_store_id, storage_key)
    WHERE storage_store_id IS NOT NULL AND storage_key IS NOT NULL;

CREATE TABLE object_delete_queue (
    queue_id TEXT PRIMARY KEY,
    storage_backend TEXT NOT NULL CHECK (storage_backend IN ('s3', 'filesystem')),
    storage_key TEXT NOT NULL CHECK (length(storage_key) > 0),
    storage_store_id TEXT NOT NULL CHECK (length(storage_store_id) > 0),
    expected_size BIGINT NOT NULL CHECK (expected_size > 0),
    expected_sha256 TEXT NOT NULL CHECK (expected_sha256 ~ '^[0-9a-f]{64}$'),
    state TEXT NOT NULL DEFAULT 'pending'
        CHECK (state IN ('pending', 'retry_wait', 'quarantined')),
    attempt_count BIGINT NOT NULL DEFAULT 0 CHECK (attempt_count >= 0),
    next_attempt_at BIGINT NOT NULL,
    last_failure_category TEXT
        CHECK (last_failure_category IS NULL OR last_failure_category IN
            ('remote_unavailable', 'integrity_mismatch')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    lease_id UUID,
    lease_until BIGINT,
    CHECK ((lease_id IS NULL) = (lease_until IS NULL)),
    UNIQUE (storage_store_id, storage_key)
);

CREATE INDEX idx_object_delete_queue_due
    ON object_delete_queue(state, next_attempt_at, created_at, queue_id)
    WHERE state IN ('pending', 'retry_wait');
